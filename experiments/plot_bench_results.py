#!/usr/bin/env python3
"""
plot_bench_results.py -- OFFLINE FIGURES.  Entry point, not implementation.

    This script runs NO physics.  It reads a CSV that a finished simulation wrote and
    draws it.  There is no MuJoCo import anywhere on its path, which is what lets it run
    in .venv-analysis (matplotlib, no mujoco) while the simulation runs in .venv
    (mujoco, no matplotlib).

WHY THE FIGURES ARE MADE AFTERWARDS, AND NOT DURING THE RUN
    Two reasons, and the second is the one that matters.  Practically, the two Python
    environments are separate.  Scientifically, a figure produced from the logged CSV can
    be regenerated by anyone from the same file and cannot influence the result: the
    six-panel figure is a RECORDING of the simulation, not a live readout of it.

WHAT IT DRAWS
    bench_track_ab19.png                 six panels: angle tracking, error, torque,
                                         velocity, power, and the command vs reference
                                         (the ROM-clip check)
    bench_track_ab19_human_reference.png the carried-through human moment/power columns,
                                         with the audit flags printed underneath, so the
                                         known defects in those two columns travel with
                                         the figure

USAGE (Windows PowerShell)
    .venv-analysis\\Scripts\\python.exe experiments\\plot_bench_results.py
    .venv-analysis\\Scripts\\python.exe experiments\\plot_bench_results.py `
        build\\bench_track_ab19\\bench_track_ab19.csv --outdir build\\figs
"""

from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from oslbench import logging as blog                                       # noqa: E402
from oslbench.controller import KD, KP                                     # noqa: E402
from oslbench.plotting import plot_bench_results                           # noqa: E402


def rel(path: str) -> str:
    """Repo-relative if the path is inside the repo, absolute otherwise.

    os.path.relpath happily returns '../../../../tmp/...' for a path outside ROOT, which
    is unreadable in a log.  This only affects printing.
    """
    r = os.path.relpath(path, ROOT)
    return path if r.startswith("..") else r


def audit_flags_from_metrics(path: str) -> list[str]:
    """Recover the reference audit flags from the metrics CSV next to the trace.

    The flags are a property of the REFERENCE, not of the plot, so they are read back
    rather than recomputed -- the figure then carries exactly the flags the run recorded.
    Missing metrics file is not an error: the figure is simply drawn without them.
    """
    if not os.path.isfile(path):
        return []
    rows = blog.read_metrics_csv(path)
    return [v for k, v in rows.items() if k.startswith("audit_flag_")]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv", nargs="?", default=blog.bench_csv_path(),
                    help="the logged trace to plot (default: the last benchmark run)")
    ap.add_argument("--outdir", default=None,
                    help="where the PNGs go (default: alongside the CSV)")
    ap.add_argument("--kp", type=float, default=KP, help="for the figure caption only")
    ap.add_argument("--kv", type=float, default=KD, help="for the figure caption only")
    ap.add_argument("--metrics", default=None,
                    help="metrics CSV to read the audit flags from "
                         "(default: <csv dir>/bench_track_ab19_metrics.csv)")
    args = ap.parse_args()

    if not os.path.isfile(args.csv):
        print(f"no such CSV: {args.csv}\n"
              f"  run the experiment first:\n"
              f"    .venv\\Scripts\\python.exe experiments\\run_bench_ab19.py --no-plot")
        return 2

    outdir = args.outdir or os.path.dirname(os.path.abspath(args.csv))
    # The audit flags describe the REFERENCE that produced this trace, so they are read
    # from beside the CSV -- NOT from --outdir, which is only where the PNGs are put.
    metrics = args.metrics or blog.metrics_csv_path(
        os.path.dirname(os.path.abspath(args.csv)))
    flags = audit_flags_from_metrics(metrics)

    print(f"plotting {rel(args.csv)}")
    print(f"  audit flags carried from {rel(metrics)}: {len(flags)}")
    made = plot_bench_results(args.csv, outdir, args.kp, args.kv, flags)
    if made[0] is None:                    # matplotlib absent; plotting.py said why
        return 1
    for p in made:
        print(f"  wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
